-- 0002_ai_outreach_schema.sql
-- Add autonomous AI email outreach, company research, action tokens, sync checkpoints & decision logs

PRAGMA foreign_keys = ON;

-- 1. COMPANY RESEARCH RECORDS
CREATE TABLE IF NOT EXISTS company_research (
    id TEXT PRIMARY KEY,
    lead_id TEXT NOT NULL REFERENCES leads(id) ON DELETE CASCADE,
    company_name TEXT NOT NULL,
    industry TEXT,
    products_services TEXT,
    business_summary TEXT,
    value_propositions JSON,
    sources JSON,
    verified_facts JSON,
    researched_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_company_research_lead ON company_research(lead_id);

-- 2. EMAIL DRAFTS (Personalized drafts generated by AI prior to or as part of campaign execution)
CREATE TABLE IF NOT EXISTS email_drafts (
    id TEXT PRIMARY KEY,
    campaign_id TEXT REFERENCES campaigns(id) ON DELETE CASCADE,
    lead_id TEXT NOT NULL REFERENCES leads(id) ON DELETE CASCADE,
    contact_id TEXT REFERENCES lead_contacts(id) ON DELETE SET NULL,
    subject TEXT NOT NULL,
    html_content TEXT NOT NULL,
    plain_content TEXT,
    research_id TEXT REFERENCES company_research(id) ON DELETE SET NULL,
    status TEXT NOT NULL CHECK(status IN ('draft', 'approved', 'queued', 'sent', 'rejected')) DEFAULT 'draft',
    ai_model TEXT,
    confidence REAL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_email_drafts_lead ON email_drafts(lead_id);
CREATE INDEX IF NOT EXISTS idx_email_drafts_campaign ON email_drafts(campaign_id);

-- 3. INTERACTIVE EMAIL ACTION TOKENS (Secure single-use or expiring action links)
CREATE TABLE IF NOT EXISTS action_tokens (
    token TEXT PRIMARY KEY,
    conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    lead_id TEXT NOT NULL REFERENCES leads(id) ON DELETE CASCADE,
    campaign_id TEXT REFERENCES campaigns(id) ON DELETE SET NULL,
    action_type TEXT NOT NULL CHECK(action_type IN ('interested', 'send_demo', 'maybe_later', 'not_interested', 'unsubscribe')),
    recipient_email TEXT NOT NULL,
    expires_at DATETIME NOT NULL,
    is_used INTEGER NOT NULL DEFAULT 0,
    used_at DATETIME,
    user_ip TEXT,
    user_agent TEXT,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_action_tokens_conv ON action_tokens(conversation_id);
CREATE INDEX IF NOT EXISTS idx_action_tokens_exp ON action_tokens(expires_at, is_used);

-- 4. EMAIL SYNC CHECKPOINTS (For resilient IMAP / Gmail polling recovery)
CREATE TABLE IF NOT EXISTS email_sync_checkpoints (
    mailbox TEXT PRIMARY KEY,
    last_uid INTEGER NOT NULL DEFAULT 0,
    last_synced_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status TEXT NOT NULL DEFAULT 'idle',
    last_error TEXT
);

-- 5. AI DECISION & CONVERSATION AUDIT LOGS
CREATE TABLE IF NOT EXISTS ai_decision_logs (
    id TEXT PRIMARY KEY,
    conversation_id TEXT REFERENCES conversations(id) ON DELETE CASCADE,
    message_id TEXT REFERENCES messages(id) ON DELETE SET NULL,
    incoming_text TEXT,
    intent_classified TEXT NOT NULL,
    confidence REAL NOT NULL,
    decision_summary TEXT NOT NULL,
    response_generated TEXT,
    knowledge_consulted JSON,
    safety_validation TEXT NOT NULL, -- 'passed', 'flagged_for_human', 'suppressed'
    action_taken TEXT NOT NULL, -- 'auto_replied', 'human_escalated', 'opted_out', 'followup_scheduled'
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ai_decision_conv ON ai_decision_logs(conversation_id);
CREATE INDEX IF NOT EXISTS idx_ai_decision_intent ON ai_decision_logs(intent_classified);
